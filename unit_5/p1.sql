CREATE OR REPLACE TRIGGER RESTRICT_WEEKEND_ACCESS
BEFORE INSERT OR UPDATE OR DELETE ON EMP
BEGIN
    IF TO_CHAR(SYSDATE, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH')
       IN ('SAT', 'SUN') THEN
        RAISE_APPLICATION_ERROR(-20001,
        'Access to the table is not allowed on weekends.');
    END IF;
END;
